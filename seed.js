function trip(time, place, action, extra = {}) {
  return {
    time,
    place,
    action,
    transport: extra.transport || "",
    travelTime: extra.travelTime || "",
    note: extra.note || "",
    status: extra.status || "confirmed",
  };
}

function day(date, title, memo, items) {
  return {
    id: date,
    date,
    title,
    memo,
    updatedAt: STAMP,
    items: items.map((item, index) => ({
      id: `${date}-${String(index + 1).padStart(2, "0")}`,
      ...item,
      updatedAt: STAMP,
    })),
  };
}

function record(id, fields) {
  return { id, ...fields, updatedAt: STAMP };
}

